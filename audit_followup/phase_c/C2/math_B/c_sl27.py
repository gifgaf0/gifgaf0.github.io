def main():
    G = [(a, b, c, d) for a in range(P) for b in range(P) for c in range(P) for d in range(P)
         if (a * d - b * c) % P == 1]
    out("=" * 78)
    out("ITEM (c) -- SL(2,7) facts (math_B leg, independent computation)")
    out("=" * 78)
    out(f"|SL(2,7)| = {len(G)}")
    assert len(G) == 336

    # ---------------- 1. element orders and classes
    ords = {g: order(g) for g in G}
    hist = Counter(ords.values())
    out("Element-order histogram (order: count):", dict(sorted(hist.items())))
    out("Set of element orders:", sorted(hist))
    out("Maximum element order:", max(hist), "| elements of order 24:", hist.get(24, 0))
    out("Divisibility sanity: 336 =", 2 ** 4 * 3 * 7, "; 24 divides 336 but no element has order 24")

    seen = set()
    classes = []
    for g in G:
        if g in seen:
            continue
        cl = {conj(h, g) for h in G}
        seen |= cl
        classes.append(sorted(cl))
    classes.sort(key=lambda c: (ords[c[0]], len(c), c[0]))
    out(f"Number of conjugacy classes: {len(classes)}")
    out("Classes (order, size, a representative):")
    for c in classes:
        out(f"   order {ords[c[0]]:2d}  size {len(c):2d}  rep {c[0]}")
    out("Sorted class sizes:", sorted(len(c) for c in classes))
    cls_of = {}
    for i, c in enumerate(classes):
        for x in c:
            cls_of[x] = i

    # ---------------- 2. u, u^k, s, t, chi
    u = (1, 1, 0, 1)
    t = (4, 0, 0, 2)
    s = (3, 0, 0, 5)
    out("\n--- u = [[1,1],[0,1]] and its powers ---")
    for k in range(1, 7):
        uk = power(u, k)
        conjugators = [g for g in G if conj(g, u) == uk]
        out(f"   u^{k} = {uk}: same SL(2,7)-class as u? {cls_of[uk] == cls_of[u]}; "
            f"#g in SL(2,7) with g u g^-1 = u^{k}: {len(conjugators)}"
            + ("   (k is a QR mod 7)" if k in QR else "   (k is a non-residue mod 7)"))
    ks = sorted({next(k for k in range(1, 7) if power(u, k) == conj(g, u))
                 for g in G if conj(g, u) in {power(u, k) for k in range(1, 7)}})
    out("   {k : g u g^-1 = u^k for some g in SL(2,7)} =", ks)
    NB = [g for g in G if conj(g, u) in {power(u, k) for k in range(7)}]
    out(f"   |N_SL(2,7)(<u>)| = {len(NB)} (all upper triangular: "
        f"{all(g[2] == 0 for g in NB)})")
    out("\n--- s = diag(3,5), t = diag(4,2) ---")
    out(f"   det s = {det(s)}, order(s) = {order(s)}; det t = {det(t)}, order(t) = {order(t)}")
    out(f"   t u t^-1 = {conj(t, u)}  (u^2 = {power(u, 2)})")
    out(f"   s u s^-1 = {conj(s, u)}  (u^2 = {power(u, 2)}, u^3 = {power(u, 3)})")
    out(f"   s == -t ?  {s == mul(MINUS_I, t)};   s^2 == t^2 ?  {mul(s, s) == mul(t, t)}")
    out(f"   s t s^-1 == t ? {conj(s, t) == t}")
    F21 = closure([u, t])
    out(f"   |<u,t>| = {len(F21)} (F21), -I in F21? {MINUS_I in F21}, s in F21? {s in F21}")
    # chi on F21: u -> u^3, t -> t.  Search SL(2,7) for an inducing element.
    hits = [g for g in G if conj(g, u) == power(u, 3) and conj(g, t) == t]
    hits_weak = [g for g in G if conj(g, u) == power(u, 3)]
    out(f"   #g in SL(2,7) with g u g^-1 = u^3 and g t g^-1 = t : {len(hits)}")
    out(f"   #g in SL(2,7) with g u g^-1 = u^3 (any action on t) : {len(hits_weak)}")
    # chi modulo Inn(F21): N_G(F21) and the automorphisms of F21 it induces
    NF = [g for g in G if all(conj(g, x) in F21 for x in (u, t))]
    induced = sorted({next(k for k in range(1, 7) if conj(g, u) == power(u, k)) for g in NF})
    out(f"   |N_SL(2,7)(F21)| = {len(NF)}; induced u -> u^k with k in {induced} "
        f"(Inn(F21) acts on <u> by k in {sorted(QR)})")
    # the outer (diagonal) automorphism Ad(d), d = diag(3,1) in GL(2,7)
    d = (3, 0, 0, 1)
    out(f"   d = diag(3,1): det d = {det(d)} (Legendre {leg(det(d))}: non-square)")
    out(f"   d u d^-1 = {conj(d, u)} (= u^3? {conj(d, u) == power(u, 3)});  d t d^-1 == t? {conj(d, t) == t}")
    Ad_d_ok = all(det(conj(d, g)) == 1 for g in G)
    out(f"   Ad(d) preserves SL(2,7): {Ad_d_ok}")
    swapped = [(i, cls_of[conj(d, c[0])]) for i, c in enumerate(classes) if cls_of[conj(d, c[0])] != i]
    out("   classes moved by Ad(d) (index -> image):", swapped,
        " => Ad(d) is NOT inner (inner automorphisms fix every class)")
    out("   orders of moved classes:", [(ords[classes[i][0]], ords[classes[j][0]]) for i, j in swapped])
    # is Ad(d) composed with any inner automorphism the identity on F21-generators? (i.e. is chi inner?)
    inner_equal = [g for g in G if all(conj(g, x) == conj(d, x) for x in (u, t))]
    out(f"   #g in SL(2,7) with Ad(g) = Ad(d) on F21 : {len(inner_equal)}")

    # ---------------- 3. principal series Ind_B^G(Legendre) as 8x8 monomial matrices
    out("\n--- 8-dim induced rep rho = Ind_B^G(lambda), lambda(diag(a,1/a) n) = (a/7) ---")
    pts = list(range(7)) + ["inf"]

    def act(g, x):
        a, b, c, dd = g
        v1, v2 = (x, 1) if x != "inf" else (1, 0)
        w1, w2 = (a * v1 + b * v2) % P, (c * v1 + dd * v2) % P
        if w2 != 0:
            return (w1 * pow(w2, P - 2, P)) % P, w2  # g v_x = w2 * v_y,  v_y = (y,1)
        return "inf", w1  # g v_x = w1 * (1,0)

    idx = {x: i for i, x in enumerate(pts)}

    def rho_int(g):
        M = np.zeros((8, 8), dtype=np.int64)
        for x in pts:
            y, cc = act(g, x)
            M[idx[y], idx[x]] = leg(cc)
        return M

    RHO = {g: rho_int(g) for g in G}
    # homomorphism on ALL pairs (exact integer check)
    bad = 0
    for g in G:
        Rg = RHO[g]
        for h in G:
            if not np.array_equal(Rg @ RHO[h], RHO[mul(g, h)]):
                bad += 1
    out(f"   homomorphism check over all 336^2 pairs: failures = {bad}")
    out(f"   rho(-I) == -Id_8: {np.array_equal(RHO[MINUS_I], -np.eye(8, dtype=np.int64))}")
    chi8 = {g: int(np.trace(RHO[g])) for g in G}
    norm8 = Fr(sum(chi8[g] ** 2 for g in G), 336)
    out(f"   <chi_rho, chi_rho> = {norm8}  (2 => sum of two inequivalent irreducibles)")
    out("   chi_rho on classes (order:value):", [(ords[c[0]], chi8[c[0]]) for c in classes])

    # commutant (exact, sympy rationals) from generators u and l, then verified on all of G
    l_ = (1, 0, 1, 1)
    out(f"   <u, l> with l = [[1,0],[1,1]] has order {len(closure([u, l_]))}")
    eqs = []
    for g in (u, l_):
        Rg = sp.Matrix(RHO[g].tolist())
        for i in range(8):
            for j in range(8):
                # (X Rg - Rg X)[i,j] = sum_k X[i,k] Rg[k,j] - Rg[i,k] X[k,j]
                row = [0] * 64
                for k in range(8):
                    row[i * 8 + k] += Rg[k, j]
                    row[k * 8 + j] -= Rg[i, k]
                eqs.append(row)
    ns = sp.Matrix(eqs).nullspace()
    out(f"   commutant dimension (exact, from generators u,l): {len(ns)}")
    basis_comm = [sp.Matrix(8, 8, list(v)) for v in ns]
    # choose T not proportional to identity; clear denominators
    T = None
    for Bm in basis_comm:
        if any(Bm[i, j] != 0 for i in range(8) for j in range(8) if i != j) or len(set(Bm[i, i] for i in range(8))) > 1:
            T = Bm
            break
    den = sp.ilcm(*[sp.fraction(x)[1] for x in T])
    T = (T * den).applyfunc(sp.Integer)
    Tn = np.array(T.tolist(), dtype=np.int64)
    comm_all = all(np.array_equal(Tn @ RHO[g], RHO[g] @ Tn) for g in G)
    out(f"   T (integer commutant element) commutes with all 336 rho(g): {comm_all}")
    out("   T =", T.tolist())
    # quadratic relation T^2 = alpha T + beta I
    T2 = T * T
    al, be = sp.symbols("al be")
    sol = sp.solve(list(T2 - al * T - be * sp.eye(8)), [al, be], dict=True)
    al_v, be_v = sol[0][al], sol[0][be]
    disc = al_v ** 2 + 4 * be_v
    out(f"   T^2 = {al_v} T + {be_v} I ; discriminant = {disc} = {sp.factorint(disc) if disc != 0 else 0}")
    # eigenvalues mu = (al +- sqrt(disc))/2 ; express sqrt(disc) = m * sqrt(-7)
    m2 = sp.Rational(disc, -7)
    m = sp.sqrt(m2)
    assert m.is_rational, "discriminant is not -7 * square"
    al_f, m_f = Fr(str(al_v)), Fr(str(m))
    mu1 = K(al_f / 2, m_f / 2)   # (alpha + m sqrt(-7))/2
    mu2 = K(al_f / 2, -m_f / 2)  # (alpha - m sqrt(-7))/2
    out(f"   eigenvalues of T: mu1 = {mu1}, mu2 = {mu2}")

    TK = [[K(int(T[i, j])) for j in range(8)] for i in range(8)]
    Id8 = ident(8)
    P1 = mat_scalar(mat_add(TK, mat_scalar(Id8, -mu2)), (mu1 - mu2).inverse())
    P2 = mat_scalar(mat_add(TK, mat_scalar(Id8, -mu1)), (mu2 - mu1).inverse())
    out(f"   P1^2 == P1: {mat_eq(mat_mul(P1, P1), P1)};  P2^2 == P2: {mat_eq(mat_mul(P2, P2), P2)};  "
        f"P1+P2 == I: {mat_eq(mat_add(P1, P2), Id8)}")
    out(f"   rank P1 = {rank_K(P1)}, rank P2 = {rank_K(P2)}, tr P1 = {trace(P1)}, tr P2 = {trace(P2)}")

    def extract(Pm):
        # basis = independent columns of Pm
        cols = [[Pm[i][j] for i in range(8)] for j in range(8)]
        R, piv = rref([list(r) for r in zip(*cols)])  # rref of Pm (rows) -> pivot columns
        bcols = [cols[j] for j in piv]
        Bm = [[bcols[j][i] for j in range(len(bcols))] for i in range(8)]  # 8 x 4
        # rows where Bm is invertible
        Rt, rpiv = rref([list(r) for r in zip(*Bm)])  # pivots of B^T = independent rows of B
        rows = rpiv
        Bsub_inv = mat_inv([Bm[r] for r in rows])
        return Bm, rows, Bsub_inv

    reps = {}
    for name, Pm in (("A", P1), ("B", P2)):
        Bm, rows, Binv = extract(Pm)
        S = {}
        ok_inv = True
        for g in G:
            RB = [[sum((K(int(RHO[g][i][k])) * Bm[k][j] for k in range(8)), ZERO) for j in range(4)] for i in range(8)]
            Mg = mat_mul(Binv, [RB[r] for r in rows])
            # exact invariance: rho(g) B == B Mg
            if not mat_eq(RB, mat_mul(Bm, Mg)):
                ok_inv = False
            S[g] = Mg
        chi = {g: trace(S[g]) for g in G}
        nrm = sum((chi[g] * chi[g].conjugate() for g in G), ZERO) / 336
        out(f"\n   component {name}: invariance rho(g)B = B sigma(g) for all g: {ok_inv}")
        out(f"   component {name}: sigma(-I) == -Id_4: {mat_eq(S[MINUS_I], mat_scalar(ident(4), K(-1)))}")
        out(f"   component {name}: sigma(I) == Id_4: {mat_eq(S[I2], ident(4))}")
        out(f"   component {name}: <chi,chi> = {nrm}  (exact; 1 => irreducible)")
        out(f"   component {name}: character on classes (order, size, value):")
        for c in classes:
            out(f"        order {ords[c[0]]:2d}  size {len(c):2d}  chi = {chi[c[0]]}")
        reps[name] = (S, chi)

    # Label sigma4 := component with chi(u) = 1 + zeta_QR = (1 + sqrt(-7))/2 (ledger L2518 convention)
    zQR = K(Fr(-1, 2), Fr(1, 2))
    target = ONE + zQR
    names = [n for n in reps if reps[n][1][u] == target]
    assert len(names) == 1
    nA = names[0]
    nB = "B" if nA == "A" else "A"
    sig4, chi4 = reps[nA]
    sig4p, chi4p = reps[nB]
    out(f"\n   sigma4  := component {nA}  (chi(u) = {chi4[u]} = 1 + zeta_QR, zeta_QR = (-1+sqrt(-7))/2)")
    out(f"   sigma4' := component {nB}  (chi(u) = {chi4p[u]})")
    out(f"   chi_sigma4' == conj(chi_sigma4) on all g: {all(chi4p[g] == chi4[g].conjugate() for g in G)}")
    out(f"   chi_sigma4 + chi_sigma4' == chi_rho on all g: {all(chi4[g] + chi4p[g] == K(chi8[g]) for g in G)}")
    # F21 restriction sanity (ledger Part IV: one trivial summand)
    triv_mult = sum((chi4[g] for g in F21), ZERO) / 21
    out(f"   multiplicity of the trivial F21-character in sigma4|F21: {triv_mult}")

    # ---------------- 5. outer automorphism Ad(d) swaps sigma4 <-> sigma4' ; Ad(s) does not
    sw = all(chi4[conj(d, g)] == chi4p[g] for g in G)
    fix_d = all(chi4[conj(d, g)] == chi4[g] for g in G)
    fix_s = all(chi4[conj(s, g)] == chi4[g] for g in G)
    out(f"\n--- twisting by automorphisms ---")
    out(f"   chi_sigma4(d g d^-1) == chi_sigma4'(g) for all g (Ad(d) maps sigma4 to sigma4'): {sw}")
