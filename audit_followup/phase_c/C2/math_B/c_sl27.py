P = 7
QR = {1, 2, 4}


# ---------------------------------------------------------------- group basics
def mul(A, B):
    a, b, c, d = A
    e, f, g, h = B
    return ((a * e + b * g) % P, (a * f + b * h) % P, (c * e + d * g) % P, (c * f + d * h) % P)


def det(A):
    a, b, c, d = A
    return (a * d - b * c) % P


def inv(A):
    a, b, c, d = A
    di = pow(det(A), P - 2, P)
    return ((d * di) % P, (-b * di) % P, (-c * di) % P, (a * di) % P)


I2 = (1, 0, 0, 1)
MINUS_I = (P - 1, 0, 0, P - 1)


def power(A, k):
    R = I2
    for _ in range(k):
        R = mul(R, A)
    return R


def order(A):
    k, R = 1, A
    while R != I2:
        R = mul(R, A)
        k += 1
    return k


def conj(g, x):
    return mul(mul(g, x), inv(g))


def closure(gens):
    S = {I2}
    frontier = [I2]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in S:
                    S.add(y)
                    nxt.append(y)
        frontier = nxt
    return S


def leg(c):
    c %= P
    if c == 0:
        raise ValueError
    return 1 if c in QR else -1


# ---------------------------------------------------------------- exact field Q(sqrt(-7))
class K:
    __slots__ = ("a", "b")

    def __init__(self, a=0, b=0):
        self.a = Fr(a)
        self.b = Fr(b)

    @staticmethod
    def c(o):
        return o if isinstance(o, K) else K(o, 0)

    def __add__(self, o):
        o = K.c(o)
        return K(self.a + o.a, self.b + o.b)

    __radd__ = __add__

    def __sub__(self, o):
        o = K.c(o)
        return K(self.a - o.a, self.b - o.b)

    def __rsub__(self, o):
        o = K.c(o)
        return K(o.a - self.a, o.b - self.b)

    def __mul__(self, o):
        o = K.c(o)
        return K(self.a * o.a - 7 * self.b * o.b, self.a * o.b + self.b * o.a)

    __rmul__ = __mul__

    def __neg__(self):
        return K(-self.a, -self.b)

    def conjugate(self):
        return K(self.a, -self.b)

    def nrm(self):
        return self.a * self.a + 7 * self.b * self.b

    def inverse(self):
        n = self.nrm()
        return K(self.a / n, -self.b / n)

    def __truediv__(self, o):
        return self * K.c(o).inverse()

    def __eq__(self, o):
        o = K.c(o)
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def iszero(self):
        return self.a == 0 and self.b == 0

    def cplx(self):
        return complex(float(self.a), float(self.b) * 7 ** 0.5)

    def __repr__(self):
        if self.b == 0:
            return f"{self.a}"
        return f"({self.a} + {self.b}*sqrt(-7))"


ZERO, ONE = K(0), K(1)
R7 = K(0, 1)  # sqrt(-7) = +i sqrt 7


def mat_mul(A, B):
    n, m, q = len(A), len(B), len(B[0])
    return [[sum((A[i][k] * B[k][j] for k in range(m)), ZERO) for j in range(q)] for i in range(n)]


def mat_eq(A, B):
    return all(A[i][j] == B[i][j] for i in range(len(A)) for j in range(len(A[0])))


def mat_scalar(A, s):
    return [[x * s for x in row] for row in A]


def mat_add(A, B):
    return [[x + y for x, y in zip(r, s)] for r, s in zip(A, B)]


def ident(n):
    return [[ONE if i == j else ZERO for j in range(n)] for i in range(n)]


def trace(A):
    return sum((A[i][i] for i in range(len(A))), ZERO)


def rref(rows):
    """Exact reduced row echelon form over K. Returns (rref rows (nonzero only), pivots)."""
    M = [list(r) for r in rows]
    nr = len(M)
    nc = len(M[0]) if nr else 0
    rank = 0
    pivots = []
    for col in range(nc):
        piv = None
        for i in range(rank, nr):
            if not M[i][col].iszero():
                piv = i
                break
        if piv is None:
            continue
        M[rank], M[piv] = M[piv], M[rank]
        pv = M[rank][col].inverse()
        M[rank] = [x * pv for x in M[rank]]
        for i in range(nr):
            if i != rank and not M[i][col].iszero():
                f = M[i][col]
                M[i] = [x - f * y for x, y in zip(M[i], M[rank])]
        pivots.append(col)
        rank += 1
    return M[:rank], pivots


def rank_K(rows):
    return len(rref(rows)[0])


def mat_inv(A):
    n = len(A)
    aug = [list(A[i]) + [ONE if i == j else ZERO for j in range(n)] for i in range(n)]
    R, piv = rref(aug)
    assert piv[:n] == list(range(n)), "singular"
    return [row[n:] for row in R]


class Span:
    """Incrementally maintained exact span (RREF basis) for membership tests."""

    def __init__(self, dim):
        self.dim = dim
        self.basis = []  # list of (pivot col, row) in reduced form

    def reduce(self, v):
        v = list(v)
        for pc, row in self.basis:
            if not v[pc].iszero():
                f = v[pc]
                v = [x - f * y for x, y in zip(v, row)]
        return v

    def add(self, v):
        v = self.reduce(v)
        for j, x in enumerate(v):
            if not x.iszero():
                inv_ = x.inverse()
                v = [y * inv_ for y in v]
                # keep basis fully reduced w.r.t. the new pivot
                nb = []
                for pc, row in self.basis:
                    if not row[j].iszero():
                        f = row[j]
                        row = [a - f * b for a, b in zip(row, v)]
                    nb.append((pc, row))
                nb.append((j, v))
                self.basis = nb
                return True
        return False

    def __len__(self):
        return len(self.basis)


def flat(A):
    return [x for row in A for x in row]


def unflat(v, n):
    return [v[i * n:(i + 1) * n] for i in range(n)]


def out(*a):
    print(*a)
    sys.stdout.flush()


