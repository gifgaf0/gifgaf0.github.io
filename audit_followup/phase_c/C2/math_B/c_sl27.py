"""
c_sl27.py -- C2 annotation batch, math_B leg, item (c): SL(2,7) facts in the spin thread.

Self-contained.  Builds SL(2,7) from scratch over F_7 (all 2x2 matrices of det 1),
imports no project code, reads no ledger file.

Checks
  1. |SL(2,7)| = 336; histogram of element orders; conjugacy classes (sizes, orders).
  2. Is u = [[1,1],[0,1]] conjugate in SL(2,7) to u^k (k = 1..6)?  Which k occur as
     g u g^-1 = u^k?  Action of s = diag(3,5) and t = diag(4,2) on u; s = -t?
     Does any g in SL(2,7) induce chi: u -> u^3, t -> t on F21 = <u,t>?  Is chi induced
     by conjugation with d = diag(3,1) in GL(2,7) (det 3, a non-square), and does Ad(d)
     swap the classes of u and u^3?
  3. Explicit 4-dim genuine irreps: rho = Ind_B^G(lambda), B = upper-triangular Borel,
     lambda([[a,*],[0,1/a]]) = Legendre(a/7), realised as an 8x8 monomial (+-1) matrix
     rep on the 8 points of P^1(F_7).  Commutant computed exactly (dim 2 => two
     inequivalent irreducible summands); split with the commutant's spectral projectors
     over Q(sqrt(-7)); 4x4 matrices extracted exactly; character norm = 1 exactly;
     sigma(-I) = -Id.
  4. Order-4 elements: count, generated subgroup, linear span of their images in
     sigma4 / sigma4' (exact rank over Q(sqrt(-7)) + numeric SVD), the algebra they
     generate (exact), the algebra generated by one anticommuting pair, clique counts
     for Gamma_x = -i sigma4(x) (pairs / triples / quadruples), omega = G1 G2 G3.
  5. chi_sigma4 o Ad(d) versus chi_sigma4' (outer automorphism swaps the two irreps?).

Exact field: K = Q(r), r^2 = -7, with r identified with +i*sqrt(7) for numerics,
so zeta_QR := zeta + zeta^2 + zeta^4 = (-1 + r)/2 for zeta = exp(2 pi i/7).
"""
import itertools
