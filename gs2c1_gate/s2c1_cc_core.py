def direction_unit(tag):
    if tag == "GK":       # along a bond (the a1 / x direction)
        return np.array([1.0, 0.0])
    if tag == "GM":       # 30 degrees
        return np.array([np.sqrt(3.0) / 2.0, 0.5])
    raise ValueError(tag)


