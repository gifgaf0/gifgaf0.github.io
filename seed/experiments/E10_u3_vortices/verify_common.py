HERE = os.path.dirname(os.path.abspath(__file__))
FIELDS = os.environ.get('VERIFY_FIELDS', '/tmp/claude-0/verify_fields')      # field files (not committed)
WIP = os.path.join(HERE, 'verify_points')                                    # per-point observables (committed)
LAM = 1.0
RUNS = {'orig': (0.1, 20.0), 'V1a': (0.1, 40.0), 'V1b': (0.05, 40.0), 'V1c': (0.05, 60.0)}

_B3 = None


def b3():
    global _B3
    if _B3 is None:
        _B3 = json.load(open(os.path.join(HERE, 'b3_results.json')))
    return _B3


def lam1():
    L = [l for l in b3()['lambdas'] if l['lam'] == 1.0][0]
    return L


def orig_records():
    return {(o['i'], o['j']): o for o in lam1()['solves']}


def ij_of(kq):
    return (int(round(kq[0] / B.DK)), int(round(kq[1] / B.DQ)))


def select_S():
    sc = lam1()['summary']['sign_changes']
    for n, c in enumerate(sc):
        c['index'] = n
    central = [c for c in sc if c['flags'] == []]
    stable = [c for c in sc if c['stable_R']]
    lowest = min(stable, key=lambda c: c['omega_star_over_mbulk'])
    largest_k = sorted(sc, key=lambda c: -c['k_star'])[:3]
    S = []
    for c in central:
        S.append(dict(role='central', **c))
    S.append(dict(role='edge: lowest omega* stable', **lowest))
    for c in largest_k:
        S.append(dict(role='edge: largest k*', **c))
    return S


def stencil_points(win, ij):
    i, j = ij
    s = [ij]
    for d in ((-1, 0), (1, 0), (0, -1), (0, 1)):
        nb = (i + d[0], j + d[1])
        if nb in win:
            s.append(nb)
    return s


def points_for(S_items):
    win = {ij: o for ij, o in orig_records().items() if o['in_window']}
    pts = set()
    for c in S_items:
        for kq in c['between']:
            pts |= set(stencil_points(win, ij_of(kq)))
    return sorted(pts)


# ---------------- per-point storage ----------------
def fpath(run, i, j):
    d = os.path.join(FIELDS, run); os.makedirs(d, exist_ok=True)
    return os.path.join(d, f'{i}_{j}.npz')


def jpath(run, i, j):
    d = os.path.join(WIP, run); os.makedirs(d, exist_ok=True)
    return os.path.join(d, f'{i}_{j}.json')


def save(run, i, j, o, x):
    f = fpath(run, i, j)
    np.savez(f + '.tmp.npz', x=x, o=json.dumps(o, default=float)); os.replace(f + '.tmp.npz', f)
    jf = jpath(run, i, j)
    json.dump(o, open(jf + '.tmp', 'w'), default=float, indent=0); os.replace(jf + '.tmp', jf)


def load(run, i, j):
    f = fpath(run, i, j)
    if not os.path.exists(f):
        return None
    z = np.load(f)
    return json.loads(str(z['o'])), z['x']


def radial(run, lam=LAM):
    dr, rmax = RUNS[run]
    return Radial(lam, dr=dr, rmax=rmax, relax_alpha=True)


def pad(Ro, xo, Rn):
    """Original solution on grid Ro -> warm start on grid Rn: linear interpolation in r for r <= Ro.rmax,
    vacuum (h = 1, a = 0) beyond; alpha kept.  h(Rn.rmax) = 1 is the Dirichlet edge of the new grid."""
    h, ap, alpha = Ro.unpack(xo)
    rn = Rn.r
    inside = rn <= Ro.rmax + 1e-12
    hn = np.empty((len(rn), 3, 3), complex); hn[:] = np.eye(3)
    apn = np.zeros((len(rn), 9))
    fl = h.reshape(len(Ro.r), 9)
    for c in range(9):
        re = np.interp(rn[inside], Ro.r, fl[:, c].real); im = np.interp(rn[inside], Ro.r, fl[:, c].imag)
        hn.reshape(len(rn), 9)[inside, c] = re + 1j * im
    for c in range(9):
        apn[inside, c] = np.interp(rn[inside], Ro.r, ap[:, c])
    hn[-1] = np.eye(3)
    return Rn.pack(hn, apn, alpha)


