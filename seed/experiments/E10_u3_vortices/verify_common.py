"""
E10 Route B, PREREG_B2B3 §6 (Amendment A) verification: shared helpers.  Label: Exploration, post-hoc verification.

Nothing here changes the instrument: the radial functional is u3radial.Radial, the per-point solve is
b3_scan.solve_point (same L-BFGS-B options), the window test is b3_scan.in_window, T-cal is b3_scan.tcal and
the R-ray direct solve follows b3_scan.analyse (f(u) = u E(k*/u, q*/u), u = 0.97, 1, 1.03, warm start from the
nearest solved grid point of the same run).

Point set S (A.3) is selected programmatically from b3_results.json (lambdas[1].summary.sign_changes):
  - the 14 sign changes whose flags are empty (central differences in both directions at both bracketing points),
  - the lowest omega*/m_bulk among stable_R ones,
  - the three with the largest k*.
For each: both bracketing grid points and every in-window neighbour their tcal stencil used.

Original solutions.  The per-point fields of the B3 scan were not kept (REPORT_B2B3 §6 dev. 7).  They are
regenerated by replaying the original warm-start chain at the original grid (dr = 0.1, r_max = 20): k = 0 row
upward in q from the abelian-Higgs initial, then each needed (i, j) from (i-1, j) (the chain recorded in
b3_results.json 'warm_from' for every needed point).  Each regenerated point is compared with the recorded E.
"""
