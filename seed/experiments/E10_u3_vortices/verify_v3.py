"""
E10 Amendment A §A.5, robustness runs V3a / V3b on the V1a grid (dr = 0.1, r_max = 40).
Label: Exploration, post-hoc, DESCRIPTIVE ONLY: neither run feeds the A.4 confirmation rule or any selection.

  V3a: lam in {0.9, 1.1}; k in {0.20, 0.25, ..., 0.50}; q = 0, 0.1, ... until the window closes or q = 40.
  V3b: lam = 0.8;         k in {0, 0.05, ..., 0.25};    q = 30.0, 30.1, ... until the window closes or q = 60.

Scan rules are b3_pipeline's (unchanged): q upward within a row, the row stops at the first out-of-window point
(omega >= m_bulk or leak > 1 % within 4 of r_max); warm start (i, j) <- (i-1, j) if row i-1 solved j, else
(i, j-1).  First points: V3a (k = 0.20, q = 0) from the abelian-Higgs initial (alpha0 = pi/4 - 0.05, as B3);
V3b (k, q = 30) from the original lam = 0.8 B3 solution padded with vacuum (rows k <= 0.10 from
b3_raw_run1_lam0.8.npz; k = 0.15-0.25 regenerated by replaying their original chain from (0.10, 30), checked
against b3_results.json).  Analysis: b3_scan.analyse unchanged (T-cal stencil, sign changes, Clough-Tocher f''
for 'stable', direct-solve cross-check), with the direct solves pre-computed by 4 workers (b3_analyse_par style).

Run:  python3 verify_v3.py run        (all rows, 4 workers, resumable per point)
      python3 verify_v3.py analyse    (-> verify_V3.json)
"""
import os
os.environ.setdefault('OMP_NUM_THREADS', '1')
import sys, json, time, glob, pickle
import numpy as np
from multiprocessing import Pool
import b3_scan as B
import verify_common as V
from u3radial import Radial
from u3common import m_bulk

DR, RMAX = 0.1, 40.0
SETS = {'V3a_lam0.9': (0.9, list(range(4, 11)), 0, 400),
        'V3a_lam1.1': (1.1, list(range(4, 11)), 0, 400),
        'V3b_lam0.8': (0.8, list(range(0, 6)), 300, 600)}


def R_of(lam):
    return Radial(lam, dr=DR, rmax=RMAX, relax_alpha=True)


def end_file(tag, i):
    d = os.path.join(V.WIP, tag); os.makedirs(d, exist_ok=True)
    return os.path.join(d, f'end_{i}.json')


def orig08():
    """Original lam = 0.8 solutions at q = 30 (dr = 0.1, r_max = 20) for i = 0..5."""
    z = np.load(os.path.join(V.HERE, 'b3_raw_run1_lam0.8.npz'))
    xs = {tuple(k): x for k, x in zip(z['keys'], z['xs'])}
    rec = {(o['i'], o['j']): o for o in [l for l in V.b3()['lambdas'] if l['lam'] == 0.8][0]['solves']}
    Ro = Radial(0.8, dr=0.1, rmax=20.0, relax_alpha=True)
    out = {}
    for i in range(0, 6):
        p = V.load('orig_lam0.8', i, 300)
        if p is not None:
            out[i] = p[1]; continue
        if i <= 2:
            x = xs[(i, 300)]
            o = Ro.observables(x, i * B.DK, 30.0); o['source'] = 'b3_raw_run1_lam0.8.npz'
        else:
            assert rec[(i, 300)]['warm_from'] == f'({(i - 1) * B.DK:.2f},30.00)', rec[(i, 300)]['warm_from']
            o, x = B.solve_point(Ro, i * B.DK, 300 * B.DQ, out[i - 1]); o['source'] = 'regenerated from (i-1, 300)'
        o['orig_E'] = rec[(i, 300)]['E']; o['rel_dE_vs_orig'] = o['E'] / rec[(i, 300)]['E'] - 1
        o['i'] = i; o['j'] = 300
        V.save('orig_lam0.8', i, 300, o, x)
        print(f'orig lam0.8 ({i * B.DK:.2f}, 30): E={o["E"]:.12f} rel dE vs b3_results {o["rel_dE_vs_orig"]:.1e}', flush=True)
        out[i] = x
    return out, Ro


def row(args):
    tag, i = args
    lam, irows, j0, jcap = SETS[tag]
    mb = m_bulk(lam)
    if os.path.exists(end_file(tag, i)):
        return tag, i
    R = R_of(lam); k = i * B.DK; j = j0; t0 = time.time()
    while True:
        q = j * B.DQ
        prev = V.load(tag, i, j)
        if prev is not None:
            o, x = prev
        else:
            while True:
                if j == j0 and tag.startswith('V3b'):
                    xo = V.load('orig_lam0.8', i, 300)
                    if xo is None:
                        time.sleep(3); continue
                    Ro = Radial(0.8, dr=0.1, rmax=20.0, relax_alpha=True)
                    x0, src = V.pad(Ro, xo[1], R), 'original lam=0.8 (dr=0.1, r_max=20) padded with vacuum'; break
                if i == irows[0]:
                    if j == j0:
                        x0, src = R.initial(alpha=B.ALPHA0), 'abelian-Higgs initial'
                    else:
                        x0, src = V.load(tag, i, j - 1)[1], f'({k:.2f},{(j - 1) * B.DQ:.2f})'
                    break
                dep = V.load(tag, i - 1, j)
                if dep is not None:
                    x0, src = dep[1], f'({(i - 1) * B.DK:.2f},{q:.2f})'; break
                ef = end_file(tag, i - 1)
                if os.path.exists(ef) and json.load(open(ef))['last_j'] < j:
                    x0, src = V.load(tag, i, j - 1)[1], f'({k:.2f},{(j - 1) * B.DQ:.2f})'; break
                time.sleep(2)
            o, x = B.solve_point(R, k, q, x0)
            o['omega_over_mbulk'] = o['omega'] / mb
            o['warm_from'] = src; o['i'] = i; o['j'] = j; o['in_window'] = B.in_window(o, mb)
            V.save(tag, i, j, o, x)
            if not o['success'] or o['iter_cap_hit']:
                print(f'[{tag}] NOT CONVERGED k={k:.2f} q={q:.2f}: {o["message"]} nit={o["nit"]}', flush=True)
        if not o['in_window'] or j >= jcap:
            capped = o['in_window'] and j >= jcap
            json.dump(dict(last_j=j, closed=not o['in_window'], capped=capped), open(end_file(tag, i), 'w'))
            print(f'[{tag}] k={k:.2f}: {"cap reached (in window)" if capped else "closed"} at q={q:.2f} '
                  f'(omega/m={o["omega_over_mbulk"]:.4f}, leak={o["leak"]:.2e}), {time.time() - t0:.0f} s', flush=True)
            return tag, i
        j += 1


def load_all(tag):
    sol = {}
    for f in glob.glob(os.path.join(V.FIELDS, tag, '*_*.npz')):
        i, j = map(int, os.path.basename(f)[:-4].split('_'))
        sol[(i, j)] = V.load(tag, i, j)
    return sol


CACHE = os.path.join(V.FIELDS, 'V3_direct_cache')


def ray_tasks(tag):
    lam = SETS[tag][0]
    sol = load_all(tag)
    win = {ij: v[0] for ij, v in sol.items() if v[0]['in_window']}
    Tc = {}
    for ij in win:
        T, *_ = B.tcal(win, *ij)
        if T is not None:
            Tc[ij] = T
    tasks = []
    for (i, j), T in Tc.items():
        for (di, dj) in ((1, 0), (0, 1)):
            nb = (i + di, j + dj)
            if nb in Tc and np.sign(T) != np.sign(Tc[nb]) and T != 0:
                t = T / (T - Tc[nb])
                ks = (i + t * di) * B.DK; qs = (j + t * dj) * B.DQ
                for u in (0.97, 1.0, 1.03):
                    kk, qq = ks / u, qs / u
                    near = min(sol, key=lambda ij: (ij[0] * B.DK - kk) ** 2 + (ij[1] * B.DQ - qq) ** 2)
                    tasks.append((tag, lam, kk, qq, near))
    return tasks


def run_ray(t):
    tag, lam, kk, qq, near = t
    f = os.path.join(CACHE, f'{lam:g}_{kk!r}_{qq!r}.pkl')
    if os.path.exists(f):
        return
    o, x = B.solve_point(R_of(lam), kk, qq, V.load(tag, *near)[1])
    pickle.dump((o, x), open(f + '.tmp', 'wb')); os.replace(f + '.tmp', f)


_orig_solve = B.solve_point


def cached_solve_point(R, k, q, x0):
    f = os.path.join(CACHE, f'{R.lam:g}_{k!r}_{q!r}.pkl')
    if os.path.exists(f):
        return pickle.load(open(f, 'rb'))
    print(f'cache miss lam={R.lam} k={k!r} q={q!r}; solving', flush=True)
    return _orig_solve(R, k, q, x0)


def classify(stable_counts):
    a, b = stable_counts.get(0.9, 0) > 0, stable_counts.get(1.1, 0) > 0
    return 'BPS-only' if (not a and not b) else ('range' if (a and b) else 'one-sided')


if __name__ == '__main__':
    cmd = sys.argv[1]
    if cmd == 'run':
        tags = sys.argv[2:] or list(SETS)
        tasks = [(t, i) for t in tags for i in SETS[t][1]]
        with Pool(int(os.environ.get('VERIFY_WORKERS', 4))) as pool:
            if any(t.startswith('V3b') for t in tags):
                pool.apply_async(orig08)
            for r in pool.imap_unordered(row, tasks, chunksize=1):
                pass
        print('V3 run done', flush=True)
    elif cmd == 'orig08':
        orig08()
    elif cmd == 'analyse':
        os.makedirs(CACHE, exist_ok=True)
        tasks = [t for tag in SETS for t in ray_tasks(tag)]
        print(f'{len(tasks)} direct solves on R rays', flush=True)
        with Pool(int(os.environ.get('VERIFY_WORKERS', 4))) as pool:
            list(pool.imap_unordered(run_ray, tasks, chunksize=1))
        B.solve_point = cached_solve_point
        res = dict(label='Exploration, post-hoc, descriptive only (A.5); does not feed A.4', grid=dict(dr=DR, rmax=RMAX), sets={})
        stable = {}
        for tag, (lam, irows, j0, jcap) in SETS.items():
            sol = load_all(tag); log = []
            summ = B.analyse(tag, R_of(lam), lam, m_bulk(lam), sol, log)
            ends = {i: json.load(open(end_file(tag, i))) for i in irows if os.path.exists(end_file(tag, i))}
            st = [c for c in summ['sign_changes'] if c['stable_R']]
            stable[lam] = len(st)
            summ.update(row_ends=ends, n_stable=len(st), lam=lam, m_bulk=m_bulk(lam), k_rows=[i * B.DK for i in irows],
                        q_range=[j0 * B.DQ, jcap * B.DQ])
            summ['points'] = [dict((kk, v[0][kk]) for kk in ('k', 'q', 'E', 'T', 'I', 'omega_over_mbulk', 'leak', 'r_charge_rms',
                                                             'alpha', 'in_window', 'Tcal', 'Tcal_envelope', 'Tcal_flags', 'success')
                                   if kk in v[0]) for _, v in sorted(sol.items())]
            res['sets'][tag] = summ
            print(f'[{tag}] {summ["n_solves"]} solves, {summ["n_in_window"]} in window, sign changes {len(summ["sign_changes"])}, '
                  f'stable {len(st)}, min Tcal/E {summ["min_Tcal_over_E"]:.4f} at {summ["argmin_Tcal_over_E"]}', flush=True)
            for l in log:
                print(l, flush=True)
        res['classification_A5'] = classify(stable)
        res['stable_counts'] = {str(k): v for k, v in stable.items()}
        json.dump(res, open(os.path.join(V.HERE, 'verify_V3.json'), 'w'), default=float)
        print('classification (A.5):', res['classification_A5'], flush=True)
