"""
e4_reconcile_checks.py -- small checks added in the E4 reconciliation (minor cross-check issues).
  (a) Singlet Higgs fields with L = R = 3 (F21): how many of 1, 1', 1'' must get vevs for three distinct
      masses?  (The report said all three; the cross-check said any two.)
  (b) Counting of residual-symmetry mixing patterns: (sector, G_l, G_nu, |U|^2) tags versus distinct
      |U|^2 structures up to row and column permutations (out/yukawa.json).
  (c) For the three surviving PSL(2,7) Z2-partial classes: the order of the group generated by the
      charged-lepton residual generator and the Z2 that fixes the neutrino column.
Reads out/reps.npz and out/yukawa.json; writes out/reconcile_checks.json.  Deterministic.
Run: python3 e4_reconcile_checks.py   (a few seconds)
"""
import itertools
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
R = np.load(os.path.join(OUT, "reps.npz"))
Y = json.load(open(os.path.join(OUT, "yukawa.json")))
rng = np.random.default_rng(7)
CHECKS, res = {}, {}


def check(name, ok, detail=""):
    CHECKS[name] = {"pass": bool(ok), "detail": detail}
    print(f"[{'PASS' if ok else 'FAIL'}] {name}  {detail}")


def nullspace(A, tol=1e-10):
    u, s, vh = np.linalg.svd(A)
    rank = int(np.sum(s > tol * max(s[0], 1)))
    return vh[rank:].conj().T


# ---------------- (a) singlet vevs and mass degeneracy, F21, L = R = 3
gens = R["F21_gens"]
r3 = R["F21_3"]
tens = {}
for h in ("1", "1'", "1''"):
    rh = R[f"F21_{h}"]
    rows = [np.kron(np.kron(r3[g].conj(), r3[g]), rh[g]) - np.eye(9) for g in gens]
    N = nullspace(np.vstack(rows))
    assert N.shape[1] == 1, (h, N.shape)
    tens[h] = N[:, 0].reshape(3, 3)
combos = {}
for k in (1, 2, 3):
    for sub in itertools.combinations(("1", "1'", "1''"), k):
        gaps = []
        for _ in range(200):
            M = sum((rng.normal() + 1j * rng.normal()) * tens[h] for h in sub)
            s = np.sort(np.linalg.svd(M, compute_uv=False))
            gaps.append(min(np.diff(s)) / s[-1])
        combos["+".join(sub)] = {"n_points": 200, "min_relative_gap": float(min(gaps)),
                                 "fraction_three_distinct(gap>1e-6)": float(np.mean(np.array(gaps) > 1e-6))}
        print(f"  singlet vevs {'+'.join(sub):<10}: smallest relative gap between |masses| over 200 points "
              f"{min(gaps):.2e}; fraction with three distinct masses {np.mean(np.array(gaps) > 1e-6):.2f}")
res["singlet_vevs_L3_R3"] = combos
check("one singlet vev (1, 1' or 1'') gives three equal |masses|",
      all(combos[h]["min_relative_gap"] < 1e-12 and combos[h]["fraction_three_distinct(gap>1e-6)"] == 0 for h in ("1", "1'", "1''")))
check("any two singlet vevs already give three distinct masses at generic couplings (cross-check's claim)",
      all(combos[c]["fraction_three_distinct(gap>1e-6)"] == 1.0 for c in ("1+1'", "1+1''", "1'+1''")))

# ---------------- (b) pattern counting
cnt = {}
for gname in ("F21", "PSL"):
    rows = Y["residual_patterns"][gname]
    keys = {tuple(np.round(np.array(p["absU2_canonical"]), 4).ravel()) for p in rows}
    by_kind = {}
    for p in rows:
        by_kind[p["kind"]] = by_kind.get(p["kind"], 0) + 1
    cnt[gname] = {"tags(kind,G_l,G_nu,|U|^2)": len(rows), "by_kind": by_kind, "distinct_absU2_structures": len(keys)}
    print(f"  {gname}: {len(rows)} (sector, G_l, G_nu, |U|^2) tags {by_kind}; {len(keys)} distinct |U|^2 structures")
res["pattern_counts"] = cnt
check("pattern counts: F21 10 tags / 3 structures; PSL 97 tags / 26 structures (cross-check's numbers)",
      cnt["F21"]["tags(kind,G_l,G_nu,|U|^2)"] == 10 and cnt["F21"]["distinct_absU2_structures"] == 3
      and cnt["PSL"]["tags(kind,G_l,G_nu,|U|^2)"] == 97 and cnt["PSL"]["distinct_absU2_structures"] == 26)

# ---------------- (c) groups generated by the residual generators of the Z2-partial survivors
P3 = R["PSL_3"]
mt = R["PSL_mt"]
order = R["PSL_order"]
e = int(np.argmin([np.linalg.norm(P3[g] - np.eye(3)) for g in range(168)]))


def closure(gs):
    S = {e}
    frontier = [e]
    while frontier:
        new = []
        for a in frontier:
            for g in gs:
                b = int(mt[a, g])
                if b not in S:
                    S.add(b)
                    new.append(b)
        frontier = new
    return len(S)


def fixed_col(gl, t):
    w, V = np.linalg.eig(P3[gl])
    V = V / np.linalg.norm(V, axis=0)
    wt, Vt = np.linalg.eig(P3[t])
    u0 = Vt[:, np.argmin(np.abs(wt - 1))]
    u0 = u0 / np.linalg.norm(u0)
    return tuple(np.sort(np.round(np.abs(V.conj().T @ u0) ** 2, 4)))


surv = [o for o in Y["z2_partial_PSL"] if o["survives(p>0.01)"]]
invols = [g for g in range(168) if order[g] == 2]
gen_orders = []
for o in sorted(surv, key=lambda x: x["chi2"]):
    target = tuple(np.round(o["fixed_column_abs2"], 4))
    o_l = int(o["G_l"][1:])
    found = set()
    for gl in (g for g in range(168) if order[g] == o_l):
        for t in invols:
            if np.allclose(fixed_col(gl, t), target, atol=2e-4):
                found.add(closure([gl, t]))
    gen_orders.append({"G_l": o["G_l"], "fixed_column_abs2": o["fixed_column_abs2"], "chi2": o["chi2"],
                       "orders_of_<g_l,t>": sorted(found)})
    print(f"  Z2-partial survivor G_l={o['G_l']} column {o['fixed_column_abs2']} chi2 {o['chi2']:.2f}: |<g_l, t>| = {sorted(found)}")
res["z2_partial_generated_groups"] = gen_orders
check("Z2-partial survivors: <Z7, t> = PSL(2,7) (168); TM1 <Z3, t> = S4 (24); TM2 <Z3, t> = A4 (12)",
      [g["orders_of_<g_l,t>"] for g in gen_orders] == [[168], [24], [12]],
      str([(g["G_l"], g["orders_of_<g_l,t>"]) for g in gen_orders]))

json.dump({**res, "checks": CHECKS, "all_pass": all(v["pass"] for v in CHECKS.values())},
          open(os.path.join(OUT, "reconcile_checks.json"), "w"), indent=1)
print(f"{sum(v['pass'] for v in CHECKS.values())}/{len(CHECKS)} checks pass")
