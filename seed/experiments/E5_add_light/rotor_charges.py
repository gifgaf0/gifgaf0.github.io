#!/usr/bin/env python3
"""
E5: electric charges of the SU(3) and SU(2) rotor states.

Gauging the U(1) generated by Q = lambda_3/2 + lambda_8/(2 sqrt 3) = diag(2/3,-1/3,-1/3) acting from the LEFT
(U -> e^{i a Q} U e^{-i a Q}) makes the collective-coordinate charge the left generator
   Q = L_3 + L_8/sqrt3 = I_3 + Y/2,   Y = 2 L_8/sqrt3 .
The WZ term fixes the RIGHT hypercharge Y_R = N_c B/3; the allowed irreps (p,q) are those containing Y = N_c/3
states, and the spin J equals the isospin of those states (Guadagnini; DPP hep-ph/9703373).

State content of (p,q) is computed two independent ways:
  (A) branching: (p,q) -> sum_{a=0..p, b=0..q} (I = (a+b)/2, Y = a - b + 2(q-p)/3)
  (B) weights: W[(p,q)] = W[Sym^p(3) x Sym^q(3bar)] - W[Sym^{p-1}(3) x Sym^{q-1}(3bar)], then peel isospin multiplets.
Checks: integrality of Q, Gell-Mann-Nishijima Q = I3 + (B+S)/2 with S = Y - B, and the SU(2) form Q = I3 + B/2.
Extra (labelled, not preregistered): N_c-dependence with fixed quark charges vs anomaly-consistent charges.
Writes charges_results.json.
"""
import json, os
from fractions import Fraction as Fr
from collections import Counter
from itertools import combinations_with_replacement

HERE = os.path.dirname(os.path.abspath(__file__))
Q_U = [(Fr(1, 2), Fr(1, 3)), (Fr(-1, 2), Fr(1, 3)), (Fr(0), Fr(-2, 3))]       # (I3, Y) of u, d, s


def content_branching(p, q):
    out = []
    for a in range(p + 1):
        for b in range(q + 1):
            out.append((Fr(a + b, 2), Fr(a - b) + Fr(2 * (q - p), 3)))
    return out


def weights_sym(p, conj=False):
    W = Counter()
    for combo in combinations_with_replacement(range(3), p):
        i3 = sum(Q_U[k][0] for k in combo); y = sum(Q_U[k][1] for k in combo)
        W[(-i3, -y) if conj else (i3, y)] += 1
    return W


def weights_irrep(p, q):
    def prod(A, B):
        C = Counter()
        for (a3, ay), m in A.items():
            for (b3, by), n in B.items():
                C[(a3 + b3, ay + by)] += m * n
        return C
    W = prod(weights_sym(p), weights_sym(q, True))
    if p >= 1 and q >= 1:
        W2 = prod(weights_sym(p - 1), weights_sym(q - 1, True))
        W.subtract(W2)
    return +W


def peel_isospin(W):
    """decompose a weight multiset into (I, Y) isomultiplets"""
    W = Counter(W)
    out = []
    while sum(W.values()) > 0:
        (i3, y) = max((k for k, v in W.items() if v > 0), key=lambda k: (k[0], k[1]))
        I = i3
        out.append((I, y))
        m = I
        while m >= -I:
            W[(m, y)] -= 1
            assert W[(m, y)] >= 0
            m -= 1
    return out


def dim(p, q):
    return (p + 1) * (q + 1) * (p + q + 2) // 2


NAMES = {(1, 1): "8", (3, 0): "10", (0, 3): "10bar", (2, 2): "27", (4, 1): "35", (1, 4): "35bar", (0, 0): "1"}
PARTICLES = {
    "8": {(Fr(1, 2), 1): "N (p, n)", (Fr(1), 0): "Sigma", (Fr(0), 0): "Lambda", (Fr(1, 2), -1): "Xi"},
    "10": {(Fr(3, 2), 1): "Delta", (Fr(1), 0): "Sigma*", (Fr(1, 2), -1): "Xi*", (Fr(0), -2): "Omega"},
    "10bar": {(Fr(0), 2): "Theta+", (Fr(1, 2), 1): "N*_10bar", (Fr(1), 0): "Sigma_10bar", (Fr(3, 2), -1): "Xi_3/2 (incl. Xi--)"},
}


def states(p, q, Nc=3):
    cb = sorted(content_branching(p, q))
    cw = sorted(peel_isospin(weights_irrep(p, q)))
    assert cb == cw, ((p, q), cb, cw)
    Yr = Fr(Nc, 3)
    spins = sorted({I for (I, Y) in cb if Y == Yr})
    return cb, spins


def main():
    res = {"convention": "Q = I3 + Y/2 with I3, Y the LEFT (flavour) generators; Y_R = N_c B/3 (WZ constraint); "
                         "content checked two ways (branching rule and weight multisets)"}
    # --- N_c = 3 allowed irreps, lowest few
    allowed = []
    for p in range(0, 6):
        for q in range(0, 6):
            cb, spins = states(p, q, 3)
            if spins:
                allowed.append({"pq": [p, q], "dim": dim(p, q), "name": NAMES.get((p, q), str(dim(p, q))),
                                "spins": [str(J) for J in spins],
                                "C2": str(Fr(p * p + q * q + p * q + 3 * p + 3 * q, 3))})
    allowed.sort(key=lambda d: (Fr(d["C2"]), d["dim"]))
    res["allowed_irreps_Nc3"] = allowed[:8]
    print("allowed irreps (N_c=3), lowest Casimir first:", [(a["name"], a["spins"]) for a in allowed[:6]])

    # --- charge table for 8, 10, 10bar, 27
    table = {}
    all_integer = True
    gmn_ok = True
    for (p, q) in [(1, 1), (3, 0), (0, 3), (2, 2)]:
        nm = NAMES[(p, q)]
        cb, spins = states(p, q)
        rows = []
        for (I, Y) in sorted(cb, key=lambda t: (-t[1], -t[0])):
            m = I
            while m >= -I:
                Qv = m + Y / 2
                S = Y - 1          # strangeness for B = 1
                integer = Qv.denominator == 1
                all_integer &= integer
                gmn_ok &= (Qv == m + (1 + S) / 2)
                rows.append({"I": str(I), "I3": str(m), "Y": str(Y), "S": str(S), "Q": str(Qv),
                             "label": PARTICLES.get(nm, {}).get((I, int(Y)) if Y.denominator == 1 else None, "")})
                m -= 1
        table[nm] = {"pq": [p, q], "dim": dim(p, q), "spins_allowed": [str(J) for J in spins],
                     "n_states": len(rows), "charges": sorted({r["Q"] for r in rows}, key=lambda s: Fr(s)),
                     "states": rows}
        assert len(rows) == dim(p, q)
        print("%-6s dim %2d  J=%s  charges %s" % (nm, dim(p, q), [str(J) for J in spins], table[nm]["charges"]))
    res["charge_table_Nc3"] = table
    res["all_charges_integer_Nc3"] = all_integer
    res["gell_mann_nishijima_holds"] = gmn_ok

    # --- SU(2) model: rotor states I = J = 1/2, 3/2, ... with Q = I3 + B/2
    su2 = []
    su2_ok = True
    for twoI in [1, 3, 5]:
        I = Fr(twoI, 2)
        qs = [str(I - k + Fr(1, 2)) for k in range(twoI + 1)]
        su2.append({"I=J": str(I), "charges": qs})
        su2_ok &= all(Fr(x).denominator == 1 for x in qs)
    res["SU2_rotor_Q_I3_plus_B_over_2"] = su2
    res["SU2_charges_integer"] = su2_ok
    # Y = 1 members of the SU(3) multiplets reproduce the SU(2) assignment Q = I3 + B/2
    y1_match = all(Fr(r["Q"]) == Fr(r["I3"]) + Fr(1, 2) for nm in table for r in table[nm]["states"] if Fr(r["Y"]) == 1)
    res["Y1_states_match_SU2_form"] = y1_match
    print("SU(2): ", su2, " Y=1 states match Q = I3 + B/2:", y1_match)

    # --- extra: N_c dependence (lowest allowed irrep for odd N_c), fixed vs anomaly-consistent quark charges
    nc_rows = []
    for Nc in [1, 3, 5, 7, 9]:
        best = None
        for p in range(0, 8):
            for q in range(0, 8):
                cb, spins = states(p, q, Nc)
                if spins:
                    C2 = Fr(p * p + q * q + p * q + 3 * p + 3 * q, 3)
                    if best is None or (C2, dim(p, q)) < best[0]:
                        best = ((C2, dim(p, q)), p, q, cb, spins)
        _, p, q, cb, spins = best
        Yr = Fr(Nc, 3)
        fixed, cons = set(), set()
        for (I, Y) in cb:
            if Y != Yr:
                continue
            m = I
            while m >= -I:
                fixed.add(m + Y / 2)
                cons.add(m + Y / 2 + Fr(1, 2) - Fr(Nc, 6))
                m -= 1
        nc_rows.append({"N_c": Nc, "lowest_irrep_pq": [p, q], "dim": dim(p, q), "spin": [str(J) for J in spins],
                        "nonstrange_charges_fixed_quark_charges": sorted(str(x) for x in fixed),
                        "nonstrange_charges_anomaly_consistent": sorted(str(x) for x in cons),
                        "integer_fixed": all(x.denominator == 1 for x in fixed),
                        "integer_consistent": all(x.denominator == 1 for x in cons)})
        print("N_c=%d lowest (%d,%d) J=%s  fixed-charge Q %s  consistent Q %s" % (
            Nc, p, q, [str(J) for J in spins], sorted(str(x) for x in fixed), sorted(str(x) for x in cons)))
    res["Nc_dependence_extra"] = {
        "note": "fixed quark charges (2/3,-1/3,-1/3): Q = I3 + Y/2; anomaly-consistent charges "
                "(1/2+1/2Nc, -1/2+1/2Nc, -1/2+1/2Nc): Q = I3 + Y/2 + (1/2 - N_c/6) B",
        "rows": nc_rows}
    with open(os.path.join(HERE, "charges_results.json"), "w") as fh:
        json.dump(res, fh, indent=1)
    print("checks: all integer (N_c=3) =", all_integer, "; GMN =", gmn_ok, "; SU(2) integer =", su2_ok)


if __name__ == "__main__":
    main()
