# ---------------------------------------------------------------------------
# §2.6 Q2 — candidate cutoff behaviour on the fixture norms
# ---------------------------------------------------------------------------


def test_candidate_cutoff_is_not_degenerate_on_fixtures(fixtures):
    """Measure how many fixture vectors pass a factor-of-2 norm cutoff
    (norm ≤ 2 · min norm). On uniform random 𝕊_911^7 vectors the norms are
    tightly concentrated, so the cutoff admits essentially all of them — a
    near-no-op on random candidates. This documents (not asserts a target
    for) the Q2 finding: the factor-of-2 is calibrated against BKZ output
    norm structure, not the ambient candidate distribution. The real Q2
    answer is deferred to the BKZ smoke test (item 4)."""
    norms = [math.sqrt(sum((x if x <= TOY_P // 2 else x - TOY_P) ** 2 for x in rec["v"]))
             for rec in fixtures["records"]]
    min_norm = min(norms)
    n_pass = sum(1 for nrm in norms if nrm <= 2 * min_norm)
    frac = n_pass / len(norms)
    # On random vectors the cutoff is near-no-op: it admits almost everything.
    assert frac > 0.95, (
        f"factor-of-2 cutoff admitted only {frac:.1%} of random fixtures; "
        "unexpectedly selective on the ambient distribution"
    )
